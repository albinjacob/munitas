"""Synthetic identifier pools.

Every value here is invented. None of it is drawn from the real encounter
artefacts, and nothing generated by this module should ever be reconciled
against them, because a synthetic corpus that happens to contain a real name
stops being synthetic.

The pools are deliberately awkward. Names that a speech model will mangle,
surnames that are also common words, and digit strings read aloud in the several
different ways clinicians actually read them. A corpus of Smiths and Joneses
would make the detectors look far better than they are.
"""

from __future__ import annotations

import random

# Names chosen for the ways they break things: non-English orthography, silent
# letters, and surnames that double as ordinary vocabulary.
PATIENT_GIVEN = [
    "Aoife", "Siobhan", "Nkechi", "Xiulan", "Bartholomew", "Grainne",
    "Thandiwe", "Eoghan", "Bridget", "Kwabena", "Sunniva", "Padraig",
    "Anneliese", "Oluwaseun", "Margarethe", "Ciaran", "Yevgenia", "Hyacinth",
]

PATIENT_FAMILY = [
    "Brennan", "Okonkwo", "Fairweather", "Zhao", "Winterbourne", "Nakagawa",
    "Bell", "Church", "Rivers", "Sparrow", "Frost", "Marchetti",
    "Achterberg", "Oyelaran", "Kowalczyk", "Featherstonehaugh", "Song", "Read",
]

CLINICIAN_FAMILY = [
    "Okafor", "Lindqvist", "Ramaswamy", "Whitcombe", "Baptiste", "Novak",
    "Ferreira", "Aldridge", "Mbeki", "Halvorsen", "Ganguly", "Prosser",
]

STREETS = [
    "Larkhill Terrace", "Copperfield Row", "Ashgrove Lane", "Pendle Close",
    "Marchmont Crescent", "Bellevue Rise", "Quarry Bank Road", "Thistlewood Way",
]

TOWNS = [
    "Kirkby Marsh", "Nether Hallam", "Ashcombe", "Draycott Magna",
    "Portslade Green", "Wintersett", "Alderly Vale", "Ravensthorpe",
]

CONDITIONS = [
    "persistent cough", "lower back pain", "recurrent migraines",
    "shortness of breath on exertion", "swelling in the left ankle",
    "palpitations at night", "burning in the upper abdomen",
]

MEDICATIONS = [
    "amlodipine", "sertraline", "metformin", "levothyroxine",
    "atorvastatin", "salbutamol", "omeprazole",
]


class Faker:
    """Seeded generator, so a corpus can be reproduced exactly.

    Reproducibility matters more than it looks. When a detector misses a span,
    the first question is whether it misses that span every time, and that is
    unanswerable if the corpus changes on every run.
    """

    def __init__(self, seed: int) -> None:
        self.rng = random.Random(seed)

    def pick(self, pool: list[str]) -> str:
        return self.rng.choice(pool)

    def patient_name(self) -> str:
        return f"{self.pick(PATIENT_GIVEN)} {self.pick(PATIENT_FAMILY)}"

    def clinician_name(self) -> str:
        return f"Doctor {self.pick(CLINICIAN_FAMILY)}"

    def date_of_birth(self) -> str:
        day = self.rng.randint(1, 28)
        month = self.rng.choice(
            ["January", "February", "March", "April", "May", "June", "July",
             "August", "September", "October", "November", "December"]
        )
        year = self.rng.randint(1938, 2006)
        return f"{day} {month} {year}"

    def mrn(self) -> str:
        return "".join(str(self.rng.randint(0, 9)) for _ in range(8))

    def mrn_spoken(self, mrn: str) -> str:
        """An MRN as a person actually says it.

        Three styles, because a detector tuned to one of them will miss the
        other two, and the real recordings contain all three.
        """
        style = self.rng.choice(["digits", "pairs", "grouped"])
        if style == "digits":
            return " ".join(mrn)
        if style == "pairs":
            return " ".join(mrn[i:i + 2] for i in range(0, len(mrn), 2))
        return f"{mrn[:4]} {mrn[4:]}"

    def phone(self) -> str:
        return f"0{self.rng.randint(1000, 1999)} {self.rng.randint(100000, 999999)}"

    def address(self) -> str:
        return f"{self.rng.randint(1, 180)} {self.pick(STREETS)}, {self.pick(TOWNS)}"

    def nhs_style_number(self) -> str:
        return f"{self.rng.randint(100, 999)} {self.rng.randint(100, 999)} {self.rng.randint(1000, 9999)}"

    def email(self, name: str) -> str:
        given, family = name.split(" ", 1)
        return f"{given.lower()}.{family.lower().replace(' ', '')}@example.invalid"
