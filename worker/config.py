# ------------------------------------------------------------------ logs --
#
# A worker's window is not a record: close it and everything it said is gone.
# Twice that lost the one piece of evidence an investigation needed, so each
# worker also writes to <MUNITAS_LOG_DIR or MUNITAS_DATA/logs>/<worker>.log,
# rolled over at 10 MB with five kept, so logs cannot fill the disk.

LOG_FORMAT = "%(asctime)s  %(levelname)-7s %(name)s  %(message)s"


def configure_logging(worker: str):
    """Log to the console and, where a log folder is configured, to a file.

    Returns the file's path, or None with the reason already logged. A folder
    that is not an absolute path on this OS is refused rather than created,
    for the same reason require_work_dir() refuses one: a Windows path read
    on Linux is a relative folder name, and would be created wherever the
    worker happened to start.
    """
    import logging
    from logging.handlers import RotatingFileHandler

    handlers: list = [logging.StreamHandler()]
    folder = os.environ.get("MUNITAS_LOG_DIR", "").strip() or (f"{_DATA}/logs" if _DATA else "")
    path, problem = None, None
    if not folder:
        problem = "no log folder is configured (MUNITAS_LOG_DIR or MUNITAS_DATA), so this worker logs to the console only"
    elif not Path(folder).is_absolute():
        problem = f"log folder {folder!r} is not an absolute path on this OS, so this worker logs to the console only"
    else:
        path = Path(folder) / f"{worker}.log"
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            handlers.append(RotatingFileHandler(path, maxBytes=10_000_000,
                                                backupCount=5, encoding="utf-8"))
        except OSError as exc:
            path, problem = None, f"cannot write to {folder!r} ({exc}), so this worker logs to the console only"
    logging.basicConfig(level=logging.INFO, format=LOG_FORMAT, handlers=handlers, force=True)
    log = logging.getLogger(f"munitas.worker.{worker}")
    if path:
        log.info("logging to %s", path)
    else:
        log.warning(problem)
    return path


def temporal_runtime():
    """A Temporal runtime whose own connection messages (retries, refusals)
    go through Python logging, and so into the log file, instead of only to
    the console. Warnings and above."""
    import logging

    from temporalio.runtime import (LogForwardingConfig, LoggingConfig, Runtime,
                                    TelemetryConfig, TelemetryFilter)

    return Runtime(telemetry=TelemetryConfig(logging=LoggingConfig(
        filter=TelemetryFilter(core_level="WARN", other_level="WARN"),
        forwarding=LogForwardingConfig(logger=logging.getLogger("temporalio.core")),
    )))
