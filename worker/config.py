class RefusedPath(RuntimeError):
    """A configured directory that cannot mean what it says on this OS."""


class InsecureApiUrl(RuntimeError):
    """MUNITAS_API points off this machine over plain HTTP."""


def require_secure_api() -> None:
    """Refuse to start if MUNITAS_API sends this worker's traffic to the
    control plane -- including a person's HuggingFace token
    (hf_ingest_activities.py's `_token_for`) and the shared worker token
    (dag_activities.py, sandbox_run.py's `x-worker-token` header) -- over
    plain HTTP to somewhere other than this machine.

    localhost stays allowed unencrypted: that traffic never leaves the
    machine, so there is nothing on the wire for a plain HTTP request to
    expose. Once MUNITAS_API names a real host, the same traffic would
    cross a real network in cleartext unless it is HTTPS, so that is the
    one thing this checks. It does not (and cannot) verify the HTTPS
    endpoint is actually configured correctly, only that a real deployment
    was not left on the default meant for one machine.

    Called once, by worker/main.py, before anything else starts. Not at
    import: scripts that read `config.API` without ever calling it (the
    verify/ suite, one-off admin scripts) should not be refused a value
    they never intended to use insecurely.
    """
    from urllib.parse import urlsplit

    parsed = urlsplit(API)
    if parsed.scheme == "https" or parsed.hostname in ("localhost", "127.0.0.1"):
        return
    raise InsecureApiUrl(
        f"Refusing to start: MUNITAS_API is {API!r}, which sends every "
        "request this worker makes -- including a HuggingFace token and "
        "the shared worker token -- to a real network address over plain "
        "HTTP.\n"
        "  Point MUNITAS_API at an https:// URL instead. For local "
        "development, see infra/tls/generate-local-cert.sh and "
        "RUNBOOK.md's \"Local HTTPS between the worker and the API\" "
        "section.\n"
        "  If this really is meant to stay on one machine, set MUNITAS_API "
        "to a localhost or 127.0.0.1 address."
    )


def _refuse(var: str, raw: str | None, default: str, why: str, how: str) -> RefusedPath:
    if raw is None and not default:
        shown = "not set, and neither is MUNITAS_DATA"
    elif raw is None:
        shown = f"not set, so {default!r} under MUNITAS_DATA was tried"
    else:
        shown = f"set to {raw!r}"
    return RefusedPath(f"Refusing to start: {var} is {shown}, and {why}.\n{how}")


def _absolute(var: str, default: str, how: str) -> Path:
    # Read the environment again rather than trusting WORK/CORPUS, because
    # Path("") is "." and the empty string would already be gone.
    raw = os.environ.get(var)
    value = default if raw is None else raw
    if raw is None and not default:
        raise _refuse(var, raw, default, "so there is no folder to use", how)
    if not value.strip():
        raise _refuse(var, raw, default, "an empty value is not a path", how)
    path = Path(value)
    if not path.is_absolute():
        # On Linux "P:" is an ordinary folder name, so a Windows path would
        # otherwise be created underneath whatever directory the process
        # started in. That is where the stray P: folder in the repo came from.
        if re.match(r"^[A-Za-z]:[\\/]", value) and os.name != "nt":
            why = "that is a Windows path, which is not absolute on this OS"
        else:
            why = "it is not an absolute path"
        raise _refuse(var, raw, default, why, how)
    return path


def require_work_dir() -> Path:
    """Return the work directory, creating it, or refuse with what to set.

    Called once by each worker process before it connects to Temporal
    (worker/main.py, worker/lite_worker.py, worker/sandbox_worker.py). Not at
    import: this module is also imported by scripts that never touch WORK.
    """
    path = _absolute("MUNITAS_WORK", _WORK_DEFAULT, _WORK_HOW_TO_SET)
    try:
        path.mkdir(parents=True, exist_ok=True)
        probe = path / f".write-check-{os.getpid()}"
        probe.write_bytes(b"")
        probe.unlink()
    except OSError as exc:
        raise _refuse("MUNITAS_WORK", os.environ.get("MUNITAS_WORK"), _WORK_DEFAULT,
                      f"it cannot be used as a writable directory ({exc})",
                      _WORK_HOW_TO_SET) from exc
    return path


def require_corpus_dir() -> Path:
    """Return the corpus directory, or refuse with what to set.

    A corpus is read and never created, so unlike the work directory it must
    already exist. Called by run_pipeline.py and schedule_pipeline.py before a
    workflow starts, because a wrong corpus otherwise surfaces much later,
    inside the ingest activity, as "no records found".
    """
    path = _absolute("MUNITAS_CORPUS", _CORPUS_DEFAULT, _CORPUS_HOW_TO_SET)
    if not path.is_dir():
        raise _refuse("MUNITAS_CORPUS", os.environ.get("MUNITAS_CORPUS"), _CORPUS_DEFAULT,
                      "no directory exists there", _CORPUS_HOW_TO_SET)
    return path

